#!/bin/bash
set -e

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" <<-EOSQL
    CREATE USER $AIRFLOW_USER WITH PASSWORD '$AIRFLOW_PASSWORD';
    CREATE DATABASE $AIRFLOW_DB OWNER $AIRFLOW_USER;
    GRANT ALL PRIVILEGES ON DATABASE $AIRFLOW_DB TO $AIRFLOW_USER;
    CREATE USER $ICEBERG_USER WITH PASSWORD '$ICEBERG_PASSWORD';
    CREATE DATABASE $ICEBERG_DB OWNER $ICEBERG_USER;
    GRANT ALL PRIVILEGES ON DATABASE $ICEBERG_DB TO $ICEBERG_USER;
EOSQL